/** אחדות הפסקה — which sentence breaks it. */
function paragraphUnity(level) {
  const [topic, keep, odd, why] = pick(UNITY);
  const hint = level >= 4 ? ' משפט "נכון בפני עצמו" עדיין פוגע בציון אם אינו משרת את טענת הפסקה.' : '';
  return {
    topic: 'אחדות הפסקה',
    text: `פסקה בנושא ${topic} כוללת את המשפטים הבאים. איזה מהם אינו שייך?`,
    options: fourOptions(odd, keep, i => `משפט ${i + 5}`),
    correctVal: odd,
    exp: `${why}${hint}`
  };
}

