function thesisStatement(level) {
  const pool = level <= 2 ? THESES.slice(0, 2) : THESES;
  const [topic, correct, wrong, why] = pick(pool);
  return {
    topic: 'ניסוח טענה',
    text: `הנושא הוא: ${topic}. איזה משפט מנסח טענה, ולא רק מודיע על הנושא?`,
    options: fourOptions(correct, wrong, i => `משפט ${i + 5}`),
    correctVal: correct,
    exp: why
  };
}

