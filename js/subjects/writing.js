/**
 * Essay-task preparation (מטלת הכתיבה).
 *
 * Gradeless: the psychometric essay, the Yael/Amir writing section and the
 * employer writing sample are all sat outside a school year.
 *
 * **The engine constraint, and what this subject does about it.**
 *
 * The essay itself has no markable answer — the app cannot score free text, and
 * pretending otherwise would give a student a number that means nothing. So the
 * essay is taught in the LESSONS (js/lessons/writing.js), including the actual
 * scoring rubric, and the quiz drills the parts of essay writing that DO have a
 * defensible right answer:
 *
 *   - which sentence states a thesis and which merely announces a topic
 *   - which paragraph order makes an argument
 *   - which connective expresses the relation the sentence needs
 *   - which register belongs in an exam essay
 *   - which sentence in a paragraph breaks its unity
 *   - what the rubric rewards
 *
 * Every one of those is a genuine sub-skill that transfers to the essay, and
 * every one is markable. That is a deliberate line, not a shortcut around it.
 *
 * Generator contract: (level) => { topic, text, options[4], correctVal, exp }.
 */
import { rand } from '../mathfmt.js';

function fourOptions(correct, candidates, spare) {
  const correctStr = String(correct);
  const seen = new Set([correctStr]);
  const out = [correctStr];
  for (const c of candidates) {
    if (out.length === 4) break;
    const v = String(c);
    if (seen.has(v)) continue;
    seen.add(v);
    out.push(v);
  }
  for (let i = 0; out.length < 4; i++) {
    if (i > 60) throw new Error(`fourOptions exhausted for "${correctStr}"`);
    const v = String(spare(i));
    if (seen.has(v)) continue;
    seen.add(v);
    out.push(v);
  }
  return out;
}
const pick = items => items[rand(0, items.length - 1)];

